public class C2Nr
{
    private final int x;
    private final int y;

    public C2Nr(int x, int y)
    {
        this.x = x;
        this.y = y;
    }

    public int getSum()
    {
        return x + y;
    }

    public int getX()
    {
        return x;
    }

    public int getY()
    {
        return y;
    }
}
